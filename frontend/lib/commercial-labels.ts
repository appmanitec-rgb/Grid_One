export function commercialLabel(
  value?: string | null,
  empty = "Não informado",
): string {
  if (!value?.trim()) return empty;
  const original = value.trim();
  const key = original
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[\s-]+/g, "_");
  if (LABELS[key]) return LABELS[key];
  if (key.startsWith("STATUS_"))
    return "Status alterado para " + commercialLabel(key.slice(7));
  const days = key.match(/^(\d+)_DIAS$/);
  if (days) return `${days[1]} dias`;
  // Custom names remain intact. Unknown enum keys have readable separators.
  if (/^[A-Z0-9]+(?:_[A-Z0-9]+)+$/.test(original)) {
    const words = original.toLocaleLowerCase("pt-BR").replace(/_/g, " ");
    return words[0].toLocaleUpperCase("pt-BR") + words.slice(1);
  }
  return original;
}

export function freightLabel(value?: string | null) {
  if (value === "FOB") return "Por conta do cliente (FOB)";
  if (value === "CIF") return "Por conta da Manitec (CIF)";
  if (value === "SEM_FRETE") return "Sem frete";
  return commercialLabel(value);
}

export function paymentMethodLabel(value: string) {
  const methods: Record<string, string> = {
    PIX: "PIX",
    BOLETO: "Boleto",
    TRANSFER: "Transferência",
    CASH: "Dinheiro",
    CARD: "Cartão",
    OTHER: "Outro",
  };
  return methods[value] || commercialLabel(value);
}
